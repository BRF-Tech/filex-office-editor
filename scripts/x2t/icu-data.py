# Writes the ICU data x2t carries: from ICU's own data package (icudt68l.dat,
# in the ICU release emscripten's port is built from), the converter alias
# table and the conversion tables icu-converters.txt names - a common data
# package in ICU's format, as ICU's icupkg would write it - and that package
# as a C file defining ICU's entry point (icudt68_dat), which takes the place
# of the port's empty stub when it is linked into x2t.
#
#   python3 icu-data.py <icudt68l.dat> <icu-converters.txt> <out.dat> [<out.c>]
#
# The package: the 16-byte-aligned header of the source package unchanged,
# then a table of contents (a count, then a name offset and a data offset per
# item, both from the start of the table), the names (in the source's order,
# which is ICU's sorted order: ICU finds an item by a binary search), and the
# items, each at a 16-byte boundary, byte for byte as in the source.
import struct
import sys


def read_package(data):
    if data[2:4] != b'\xda\x27' or data[12:16] != b'CmnD':
        raise SystemExit('not an ICU common data package')
    if data[8] != 0:
        raise SystemExit('a big-endian package: WebAssembly needs the little-endian one (icudt*l.dat)')
    header_size = struct.unpack_from('<H', data, 0)[0]
    count = struct.unpack_from('<I', data, header_size)[0]
    items = []
    for i in range(count):
        name_off, data_off = struct.unpack_from('<II', data, header_size + 4 + 8 * i)
        end = data.index(b'\0', header_size + name_off)
        items.append([data[header_size + name_off:end].decode('ascii'), header_size + data_off])
    ends = sorted(off for _, off in items) + [len(data)]
    following = {ends[i]: ends[i + 1] for i in range(len(ends) - 1)}
    return header_size, [(name, data[off:following[off]]) for name, off in items]


def read_list(path, prefix):
    names = []
    for line in open(path, encoding='utf-8'):
        line = line.split('#', 1)[0].strip()
        if line:
            names.append(prefix + line)
    return names


def write_package(header, items):
    count = len(items)
    toc_size = 4 + 8 * count
    names = b''
    name_offsets = []
    for name, _ in items:
        name_offsets.append(toc_size + len(names))
        names += name.encode('ascii') + b'\0'
    body_start = toc_size + len(names)
    body_start += -body_start % 16
    body = b''
    data_offsets = []
    for _, blob in items:
        data_offsets.append(body_start + len(body))
        body += blob + b'\0' * (-len(blob) % 16)
    toc = struct.pack('<I', count)
    for n, d in zip(name_offsets, data_offsets):
        toc += struct.pack('<II', n, d)
    toc += names
    toc += b'\0' * (body_start - len(toc))
    return header + toc + body


def write_c(package, entry_point):
    out = ['/* Generated by scripts/x2t/icu-data.py: ICU data (converters) for x2t. */',
           '#include <stdint.h>',
           'const struct { double align; uint8_t bytes[%d]; } %s __attribute__((aligned(16))) = { 0.0, {' % (len(package), entry_point)]
    for i in range(0, len(package), 24):
        out.append(','.join(str(b) for b in package[i:i + 24]) + ',')
    out.append('} };')
    return '\n'.join(out) + '\n'


def main():
    src, listing, out_dat = sys.argv[1:4]
    out_c = sys.argv[4] if len(sys.argv) > 4 else None
    data = open(src, 'rb').read()
    header_size, items = read_package(data)
    prefix = items[0][0].split('/', 1)[0] + '/'
    by_name = dict(items)
    wanted = set(read_list(listing, prefix))
    missing = sorted(wanted - set(by_name))
    if missing:
        raise SystemExit('not in %s: %s' % (src, ', '.join(missing)))
    kept = [(name, blob) for name, blob in items if name in wanted]
    package = write_package(data[:header_size], kept)
    with open(out_dat, 'wb') as f:
        f.write(package)
    if out_c:
        major = prefix[len('icudt'):-2]
        with open(out_c, 'w', newline='\n') as f:
            f.write(write_c(package, 'icudt%s_dat' % major))
    print('%s: %d of %d items, %d bytes' % (out_dat, len(kept), len(items), len(package)))


if __name__ == '__main__':
    main()
