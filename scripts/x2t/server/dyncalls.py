# Writes dyncalls.c for the server build of x2t (scripts/x2t/steps.sh,
# x2t_server): one exported function per invoke_<sig> the module imports,
# fx_dyncall_<sig>(index, args...), which calls the table entry at index,
# and fx_unwind(), for the host after a longjmp.
#
# setjmp/longjmp goes through invoke_<sig>, which the host answers
# (server/x2t/env.go). The host cannot make the indirect call itself: with
# -sEMULATE_FUNCTION_POINTER_CASTS every table entry has binaryen's one
# signature, and a call by the import's signature traps ("indirect call
# type mismatch", measured with wazero). Made inside the module, the call is
# rewritten by the same pass as every other indirect call.
#
# Each fx_dyncall_* also keeps the stack pointer it was called with, in the
# module: invoke_* must put it back after a longjmp, and reading it from the
# host would be one more call into the module for every invoke - and x2t
# makes millions of them in a document with pictures (measured: 2,575,815
# for sample.docx to odt). After a longjmp the host calls fx_unwind(), which
# drops the frame the longjmp left behind and restores its stack pointer.
#
#   python3 dyncalls.py <x2t.wasm of a first link> <dyncalls.c>

import sys

C_TYPE = {"i": "int", "p": "int", "j": "long long", "f": "float", "d": "double"}


def leb(b, i):
    r = s = 0
    while True:
        x = b[i]
        i += 1
        r |= (x & 0x7F) << s
        s += 7
        if x < 0x80:
            return r, i


def name(b, i):
    n, i = leb(b, i)
    return b[i : i + n].decode(), i + n


def invokes(path):
    b = open(path, "rb").read()
    if b[:4] != b"\0asm":
        sys.exit(f"{path}: not WebAssembly")
    i = 8
    out = []
    while i < len(b):
        sid = b[i]
        size, i = leb(b, i + 1)
        end = i + size
        if sid == 2:
            n, j = leb(b, i)
            for _ in range(n):
                mod, j = name(b, j)
                field, j = name(b, j)
                kind = b[j]
                j += 1
                if kind == 0:
                    _, j = leb(b, j)
                    if mod == "env" and field.startswith("invoke_"):
                        out.append(field[len("invoke_") :])
                elif kind == 1:
                    j += 1
                    flags = b[j]
                    j += 1
                    _, j = leb(b, j)
                    if flags & 1:
                        _, j = leb(b, j)
                elif kind == 2:
                    flags = b[j]
                    j += 1
                    _, j = leb(b, j)
                    if flags & 1:
                        _, j = leb(b, j)
                elif kind == 3:
                    j += 2
            return sorted(set(out))
        i = end
    return []


def main(wasm, out):
    lines = [
        "// Generated by scripts/x2t/server/dyncalls.py from the module's invoke_* imports.",
        "#include <stdint.h>",
        "#include <emscripten/stack.h>",
        "",
        "void _emscripten_stack_restore(uintptr_t sp);",
        "#define FX_DEPTH 4096",
        "static uintptr_t fx_sp[FX_DEPTH];",
        "static unsigned fx_depth;",
        "#define FX_ENTER() (fx_sp[fx_depth++ % FX_DEPTH] = emscripten_stack_get_current())",
        "#define FX_LEAVE() (fx_depth--)",
        '__attribute__((export_name("fx_unwind"))) void fx_unwind(void) { if (fx_depth) fx_depth--; _emscripten_stack_restore(fx_sp[fx_depth % FX_DEPTH]); }',
        "",
    ]
    for sig in invokes(wasm):
        ret, params = sig[0], sig[1:]
        if ret != "v" and ret not in C_TYPE or any(p not in C_TYPE for p in params):
            sys.exit(f"invoke_{sig}: a signature this generator does not know")
        rtype = "void" if ret == "v" else C_TYPE[ret]
        args = ", ".join(f"{C_TYPE[p]} a{k}" for k, p in enumerate(params))
        types = ", ".join(C_TYPE[p] for p in params) or "void"
        call = ", ".join(f"a{k}" for k in range(len(params)))
        body = f"(({rtype} (*)({types}))(intptr_t)index)({call})"
        if rtype == "void":
            inner = f"FX_ENTER(); {body}; FX_LEAVE();"
        else:
            inner = f"FX_ENTER(); {rtype} r = {body}; FX_LEAVE(); return r;"
        lines.append(
            f'__attribute__((export_name("fx_dyncall_{sig}"))) {rtype} fx_dyncall_{sig}(int index{", " + args if args else ""}) '
            f"{{ {inner} }}"
        )
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    print(f"{out}: {sum(1 for l in lines if 'fx_dyncall_' in l)} dyncalls")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
